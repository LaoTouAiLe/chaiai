import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

test('MCP 创建、连接、名单、编辑与删除走真实 API 和 stdio', async ({ page, request }, info) => {
  const name = `demo${info.project.name.split('x')[0]}`
  const python = resolve(process.platform === 'win32' ? '../.venv/Scripts/python.exe' : '../.venv/bin/python')
  await request.delete(`/api/mcp/servers/${name}`)
  await request.put('/api/capabilities', { data: { changes: { mcp: false } } })
  await page.goto('/?state=settings-models&live=1')
  const dialog = page.getByRole('dialog', { name: '设置' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('tab', { name: 'MCP 外部工具', exact: true }).click()
  await expect(dialog.getByText(/子 Agent 暂不支持/)).toBeVisible()
  await dialog.getByRole('button', { name: '添加 Server', exact: true }).click()
  await dialog.getByLabel('名称', { exact: true }).fill(name)
  await dialog.getByLabel('命令', { exact: true }).fill(python)
  await dialog.getByLabel('参数', { exact: true }).fill(JSON.stringify([resolve('../tests/mcp_fake_server.py')]))
  await dialog.getByLabel('环境变量', { exact: true }).fill('TEST_TOKEN=browser-dummy-secret')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByRole('button', { name: `编辑 ${name}` })).toBeVisible()
  await expect(dialog.getByLabel(`${name} 开关`)).not.toBeChecked()
  await expect(dialog).not.toContainText('browser-dummy-secret')
  await dialog.getByLabel('MCP 总开关').click()
  await expect(dialog.getByLabel('MCP 总开关')).toBeChecked()
  await dialog.getByLabel(`${name} 开关`).click()
  await expect(dialog.getByLabel(`${name} 开关`)).toBeChecked()
  await expect(dialog.getByText('已连接', { exact: true })).toBeVisible()
  const echo = dialog.getByRole('button', { name: `mcp__${name}__echo 启用` })
  await echo.click()
  await expect(echo).toHaveAttribute('aria-pressed', 'false')
  await dialog.getByRole('button', { name: `${name} 工具名单` }).click()
  await dialog.getByLabel(`${name} 使用白名单`).check()
  await dialog.getByLabel(`${name} 白名单`).fill('echo')
  await dialog.getByLabel(`${name} 停用名单`).fill('')
  await dialog.getByRole('button', { name: '保存工具名单' }).click()
  await expect(echo).toHaveAttribute('aria-pressed', 'true')
  await expect(dialog.getByText('不在白名单').first()).toBeVisible()
  await dialog.getByRole('button', { name: `编辑 ${name}` }).click()
  await expect(dialog.getByLabel('环境变量', { exact: true })).toHaveValue('')
  await expect(dialog.getByLabel('命令', { exact: true })).toHaveValue(python)
  await dialog.getByLabel('环境变量', { exact: true }).fill('NEW_TOKEN=another-dummy-secret')
  await dialog.getByRole('button', { name: '保存', exact: true }).click()
  await expect(dialog.getByLabel(`${name} 开关`)).not.toBeChecked()
  await dialog.getByRole('button', { name: `编辑 ${name}` }).click()
  await expect(dialog.getByLabel('删除环境变量 TEST_TOKEN')).toBeVisible()
  await expect(dialog.getByLabel('删除环境变量 NEW_TOKEN')).toBeVisible()
  await dialog.getByRole('button', { name: '取消编辑' }).click()
  await page.screenshot({ path: info.outputPath('mcp-settings.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: `删除 ${name}` }).click()
  await dialog.getByRole('button', { name: '取消删除' }).click()
  await expect(dialog.getByRole('button', { name: `编辑 ${name}` })).toBeVisible()
  await dialog.getByRole('button', { name: `删除 ${name}` }).click()
  await dialog.getByRole('button', { name: '确认删除' }).click()
  await expect(dialog.getByRole('button', { name: `编辑 ${name}` })).toHaveCount(0)
  const state = await (await request.get('/api/mcp')).json()
  expect(state.servers).toEqual([])
})
